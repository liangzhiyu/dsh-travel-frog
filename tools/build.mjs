import { readFile, writeFile } from 'node:fs/promises'
const root = new URL('../', import.meta.url)
const core = (await readFile(new URL('core.js', root), 'utf8')).replace(/^export /gm, '')
const body = await readFile(new URL('client-source.js', root), 'utf8')
await writeFile(new URL('client.js', root), `// Generated by tools/build.mjs; edit core.js and client-source.js.\nwindow.__ModuleLoader__.load({ id: 'dsh-travel-frog', factory(require) {\n${core}\n${body}\n} });\n`)
