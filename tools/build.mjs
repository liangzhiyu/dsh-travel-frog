import { readFile, writeFile } from 'node:fs/promises'

const root = new URL('../', import.meta.url)
const read = (path, encoding) => readFile(new URL(path, root), encoding)
const asset = async (path, type) => `data:${type};base64,${(await read(path)).toString('base64')}`
const [core, body, css, home, bridge, post, mail] = await Promise.all([
  read('core.js', 'utf8'),
  read('client-source.js', 'utf8'),
  read('client.css', 'utf8'),
  asset('assets/doorstep.webp', 'image/webp'),
  asset('assets/woodbridge.webp', 'image/webp'),
  asset('assets/moss-post.webp', 'image/webp'),
  asset('assets/mail.svg', 'image/svg+xml'),
])
const embedded = {
  TRAVEL_CSS: css,
  HOME_ART: home,
  POSTCARD_ART: { 'fern-bridge': bridge, 'moss-post': post },
  MAIL_ICON: mail,
}
const declarations = Object.entries(embedded).map(([key, value]) =>
  `const ${key} = ${JSON.stringify(value)}`).join('\n')
await writeFile(new URL('client.js', root), `// Generated by tools/build.mjs; edit the source files instead.
window.__ModuleLoader__.load({ id: 'dsh-travel-frog', factory(require) {
${core.replace(/^export /gm, '')}
${declarations}
${body}
} });
`)
